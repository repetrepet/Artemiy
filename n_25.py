"""
Обозначим через F целую часть среднего арифметического всех натуральных делителей целого числа, кроме единицы и самого числа. Если таких делителей у числа нет, то считаем значение F равным нулю.

Напишите программу, которая перебирает целые числа, большие 750 000, в порядке возрастания и ищет среди них такие, для которых значение F при делении на 7 даёт в остатке 6. Выведите первые 5 найденных чисел в порядке возрастания и справа от каждого числа  — соответствующее значение F.
"""

# Идея решения:
# Исключаем из списка делителей единицу и само число. Вычисляем целую часть
# среднего арифметического оставшихся делителей и проверяем остаток от деления на 7.

# Находим все натуральные делители числа n.
def f(n):
    # Множество хранит делители без повторений.
    s = set()
    # Перебираем возможные меньшие делители до квадратного корня включительно.
    for i in range(1, int(n ** 0.5) + 1):
        # Проверяем деление без остатка.
        if n % i == 0:
            # Добавляем меньший делитель пары.
            s.add(i)
            # Добавляем соответствующий ему больший делитель.
            s.add(n // i)
    # Возвращаем делители в порядке возрастания.
    return sorted(list(s))
# Начинаем подсчёт найденных чисел с нуля.
