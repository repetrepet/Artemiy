# =============================================================================
"""
Напишите программу, которая ищет среди целых чисел, принадлежащих числовому отрезку [174457; 174505], числа, имеющие ровно два различных натуральных делителя, не считая единицы и самого числа. Для каждого найденного числа запишите эти два делителя в два соседних столбца на экране с новой строки в порядке возрастания произведения этих двух делителей. Делители в строке также должны следовать в порядке возрастания.

Например, в диапазоне [5; 9] ровно два различных натуральных делителя имеют числа 6 и 8, поэтому для этого диапазона вывод на экране должна содержать следующие значения:
2 3
2 4
"""

# Идея решения:
# Для каждого числа проверяем возможные делители от 2 до его квадратного корня.
# Если число делится на i, то вместе с i делителем является n // i.
# Пара делителей позволяет найти сразу малый и большой делитель.
# Множество set убирает повторы, которые возникают у квадратов.
# Исключаем 1 и само число, сортируем найденные делители и проверяем их количество.

def f(n):
    # Создаём множество для хранения различных собственных делителей числа.
    divisors = set()
    # Перебираем возможные меньшие делители, начиная с 2.
    for i in range(2, int(n ** 0.5) + 1):
        # Остаток 0 означает, что i делит n без остатка.
        if n % i == 0:
            # Добавляем меньший делитель.
            divisors.add(i)
            # Добавляем соответствующий ему делитель из пары.
            divisors.add(n // i)
    # Возвращаем делители в возрастающем порядке.
    return sorted(divisors)

# Проверяем все целые числа от левой границы отрезка до правой включительно.
for n in range(174457, 174505 + 1):
    # Получаем список собственных делителей числа.
    result = f(n)
    # Оставляем числа, у которых найдено ровно два таких делителя.
    if len(result) == 2:
        # Выводим делители по возрастанию; их произведение равно n.
        print(*result)


