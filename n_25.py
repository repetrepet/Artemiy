"""
Пусть N — сумма всех нечётных делителей числа, не считая единицы и самого числа. Если таких делителей у числа нет, то значение N считается равным нулю.

Напишите программу, которая среди натуральных чисел, превышающих 10^6, ищет первые пять чисел, для которых N больше самого числа.

Для каждого найденного числа в отдельной строке таблицы запишите само число, а также значение N.

Например, для числа 945 ответом будет пара чисел:
945 974
"""

# Идея решения:
# Вычисляем сумму нечётных делителей и сравниваем её с самим числом.

# Определяем функцию вычисления суммы нечётных делителей.
def n(k):
    # Начинаем суммирование с нуля.
    summa = 0
    # Перебираем возможные делители от 2 до половины числа включительно.
    for delitel in range(2, int(k // 2) + 1):
        # Проверяем, что делитель нечётный и делит число без остатка.
        if k % delitel == 0 and delitel % 2 != 0:
            # Добавляем подходящий делитель к сумме.
            summa += delitel
    # Возвращаем сумму найденных делителей.
    return summa

# Перебираем числа в исходном диапазоне.
for i in range(10 ** 6, 10 ** 7):
    # Проверяем, превышает ли сумма делителей само число.
    if n(i) > i:
        # Выводим число и сумму его нечётных делителей.
        print(i, n(i))
        # Завершаем перебор после первого найденного числа, как в исходном коде.
        break
