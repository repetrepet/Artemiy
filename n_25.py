"""
Назовём маской числа последовательность цифр, в которой также могут встречаться следующие символы:

    символ «?» означает ровно одну произвольную цифру
    символ «*» означает любую последовательность цифр произвольной длины; в том числе «*» может задавать и пустую последовательность

Например, маске 123*4?5 соответствуют числа 123405 и 12300405.

Среди натуральных чисел, не превышающих 10^10, найдите все числа, соответствующие маске 89*6?7?9?, делящиеся на 9874 без остатка.

В ответе запишите в первом столбце таблицы все найденные числа в порядке возрастания, а во втором столбце — соответствующие им результаты деления этих чисел на 9874.

Количество строк в таблице для ответа избыточно.
"""

# Идея решения:
# Перебираем кратные 9874 в заданном диапазоне и проверяем их запись по маске.

# Импортируем функцию проверки строки по маске.
from fnmatch import fnmatchcase

# Перебираем кратные 9874 до указанной верхней границы включительно.
for n in range(9874, 10 ** 10 + 1, 9874):
    # Проверяем запись числа по маске: ? — одна цифра, * — любая последовательность цифр.
    if fnmatchcase(str(n), '89*6?7?9?'):
        # Выводим число и целочисленный результат его деления на 9874.
        print(n, n // 9874)


