"""
Пусть R — сумма всех делителей числа, оканчивающихся на 8, не считая самого числа. Если таких делителей у числа нет, то значение R считается равным нулю.


Напишите программу, которая среди натуральных чисел на отрезке [114578, 114616] ищет все числа, для которых значение R оканчивается на 6.

Для каждого найденного числа в отдельной строке таблицы запишите само число, а также значение R.

Например, для числа 56 ответом будет пара чисел:
56 36
"""

# Идея решения:
# Для каждого числа суммируем подходящие делители и проверяем последнюю цифру суммы.

def r(n): # получаем число R
    # Начинаем суммирование делителей с нуля.
    count = 0
    for i in range(1, (n // 2) + 1): # проходимся до половины числа, больше нет смысла проверять
        if n % i == 0 and i % 10 == 8: # число делится на делитель и заканчивается на 8
            count += i # суммируем делители
    # Возвращаем полученную сумму делителей.
    return count


# Перебираем числа в исходном диапазоне.
for n in range(114578, 114616):
    if r(n) % 10 == 6: # если R заканчивается на 6
        print(n, r(n)) # выводим число и значение R для него


