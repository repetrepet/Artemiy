# =============================================================================
# Задача 2. Кратчайший путь из вершины 214 в вершину 100
# =============================================================================
"""
Найдите и запишите в ответе целую часть длины кратчайшего пути из вершины с номером 214 в вершину с номером 100. Существование хотя бы одного такого пути гарантируется.
"""

# Идея решения:
# Преобразуем строки файла в список рёбер: начало, конец и вес.
# Храним найденные расстояния от вершины 214 и многократно просматриваем
# все рёбра, обновляя расстояние, если найден более короткий путь.

# Пример преобразования входных данных (справочный блок к этой задаче).
# Было:
# 69   826     3660.3
# 595   872    1944.0
# 229   733    3644.0
# Должно быть:
# lst = [
#     [69, 826, 3660.3],
#     [595, 872, 1944.0],
#     [229, 733, 3644.0]
# ]

# Открываем файл с рёбрами и создаём список для их хранения.
f = open('data.txt')
lst = []

# Разбиваем строку по пробельным символам и преобразуем значения в числа.
for i in f:
    n1, n2, n3 = i.split()
    lst.append([int(n1), int(n2), float(n3)])

# Готовим расстояния для номеров вершин от 0 до 1000.
n = 1000 + 1
start = 214
dist = [float('inf')] * n
# Расстояние от начальной вершины до самой себя равно нулю.
dist[start] = 0

# Выполняем n - 1 проходов по всем рёбрам графа.
for i in range(n - 1):
    for a, b, c in lst:
        # Если путь через вершину a короче, обновляем расстояние до b.
        if dist[a] + c < dist[b]:
            dist[b] = dist[a] + c

# Выводим найденное расстояние до вершины 100.
print(dist[100])
