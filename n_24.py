# Открываем файл для чтения (добавлена кодировка для надёжности)
f = open('data.txt', 'r', encoding='utf-8')
# Считываем всё содержимое файла в одну строку
s = f.read()
f.close()

# Разбиваем строку по подстроке 'BC'. 
# Получаем список частей, которые находились между вхождениями 'BC'.
lst = s.split('BC')

# Переменная для хранения максимальной найденной длины последовательности
mx = 0

# Проходим по списку скользящим окном. 
# Нам нужно выбрать 191 элемент (чтобы между ними было ровно 190 разделителей 'BC').
# Поэтому цикл идёт до len(lst) - 190.
for index in range(len(lst) - 190):
    # Формируем окно из 191 последовательного элемента списка
    elements = lst[index:index + 191]
    
    # Вычисляем общую длину последовательности: 
    # сумма длин всех частей + длина разделителей 'BC' (190 штук по 2 символа).
